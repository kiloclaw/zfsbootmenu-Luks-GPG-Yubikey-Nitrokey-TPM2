//! The allowed dependencies between the crates of the workspace.
//!
//! Each crate belongs to one layer. A crate may depend on crates of lower
//! layers, and on a crate of its own layer only where [`SAME_LAYER`] says so.
//! Test support crates may only be development dependencies; tools depend on
//! no crate of the workspace. Third-party crates are allowed per crate in
//! [`THIRD_PARTY`].
//!
//! `cargo xtask check-deps` checks the workspace against these tables, and
//! the section of `docs/dev/architecture.md` between the markers
//! [`BEGIN`] and [`END`] is generated from them, so that the documentation
//! and the check cannot drift apart. Changing an allowed edge is a change of
//! these tables, which a reviewer sees.

use std::fmt::Write as _;
use std::path::Path;

use crate::error::{Error, Result};
use crate::workspace::{DependencyKind, Package, Workspace};

/// One layer of the architecture.
#[derive(Clone, Copy, Debug)]
pub struct Layer {
    /// The layer's name.
    pub name: &'static str,
    /// What the layer is for.
    pub purpose: &'static str,
    /// The crates in it.
    pub crates: &'static [&'static str],
}

/// The layers from the bottom up.
///
/// These describe the workspace as it is at the start of the refactoring;
/// REFACTOR-ROADMAP.md changes them phase by phase.
pub const LAYERS: &[Layer] = &[
    Layer {
        name: "unsafe",
        purpose: "The only crate with `unsafe` code: C library calls",
        crates: &["zbm-sys"],
    },
    Layer {
        name: "foundation",
        purpose: "Commands, errors, file tests, logging formats",
        crates: &["zbm-core", "zbm-log"],
    },
    Layer {
        name: "platform",
        purpose: "System interfaces and their real implementations, \
                  state files, the kernel command line",
        crates: &["zbm-system", "zbm-state", "zbm-cmdline"],
    },
    Layer {
        name: "adapters",
        purpose: "External programs: ZFS",
        crates: &["zbm-zfs"],
    },
    Layer {
        name: "domain",
        purpose: "LUKS volumes, kernel command lines of boot environments",
        crates: &["zbm-luks", "zbm-kcl"],
    },
    Layer {
        name: "orchestration",
        purpose: "Start-up and boot; image generation",
        crates: &["zbm-boot", "generate-zbm"],
    },
    Layer {
        name: "front ends",
        purpose: "The menu and the multi-call binary",
        crates: &["zbm-menu", "zbm"],
    },
];

/// Dependencies between crates of the same layer: (from, to).
pub const SAME_LAYER: &[(&str, &str)] = &[("zbm-log", "zbm-core"), ("zbm-state", "zbm-system")];

/// Crates that only tests may use.
pub const TEST_SUPPORT: &[&str] = &["zbm-testutil"];

/// Developer tools, which no crate may use.
pub const TOOLS: &[&str] = &["xtask"];

/// The third-party crates each crate may depend on.
pub const THIRD_PARTY: &[(&str, &[&str])] = &[
    ("generate-zbm", &["yaml-rust2"]),
    ("xtask", &["proc-macro2", "serde_json", "syn"]),
];

/// The marker that opens the generated section of the architecture page.
pub const BEGIN: &str = "<!-- BEGIN generated by `cargo xtask check-deps --bless` -->";

/// The marker that closes the generated section.
pub const END: &str = "<!-- END generated -->";

/// The architecture page, relative to the workspace root.
pub const PAGE: &str = "docs/dev/architecture.md";

/// Where a crate stands in the tables.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum Place {
    /// In the layer with this index (0 is the bottom).
    Layer(usize),
    /// A test support crate.
    TestSupport,
    /// A developer tool.
    Tool,
}

/// The place of `name`, if the tables list it.
fn place(name: &str) -> Option<Place> {
    if let Some(index) = LAYERS.iter().position(|layer| layer.crates.contains(&name)) {
        return Some(Place::Layer(index));
    }
    if TEST_SUPPORT.contains(&name) {
        return Some(Place::TestSupport);
    }
    TOOLS.contains(&name).then_some(Place::Tool)
}

/// Every problem of the workspace's dependencies, one line each.
pub fn problems(workspace: &Workspace) -> Vec<String> {
    let mut problems = Vec::new();
    for package in &workspace.packages {
        if place(&package.name).is_none() {
            problems.push(format!(
                "{} is in no layer: add it to xtask/src/deps.rs",
                package.name
            ));
        }
    }
    for name in table_crates() {
        if workspace.package(name).is_none() {
            problems.push(format!(
                "{name} is in xtask/src/deps.rs but not in the workspace"
            ));
        }
    }
    for package in &workspace.packages {
        problems.extend(package_problems(package));
    }
    problems
}

/// Every crate the tables name.
fn table_crates() -> impl Iterator<Item = &'static str> {
    LAYERS
        .iter()
        .flat_map(|layer| layer.crates.iter().copied())
        .chain(TEST_SUPPORT.iter().copied())
        .chain(TOOLS.iter().copied())
}

/// The problems of one package's dependencies.
fn package_problems(package: &Package) -> Vec<String> {
    let mut problems = Vec::new();
    let Some(from) = place(&package.name) else {
        return problems;
    };
    for dependency in &package.dependencies {
        let edge = format!("{} -> {}", package.name, dependency.name);
        if !dependency.member {
            if !third_party_allowed(&package.name, &dependency.name) {
                problems.push(format!(
                    "{edge}: third-party crate not allowed in THIRD_PARTY"
                ));
            }
            continue;
        }
        let Some(to) = place(&dependency.name) else {
            continue;
        };
        if let Some(reason) =
            edge_problem(&package.name, from, &dependency.name, to, dependency.kind)
        {
            problems.push(format!("{edge}: {reason}"));
        }
    }
    problems
}

/// Why the edge `from` → `to` of `kind` is not allowed, if it is not.
fn edge_problem(
    from_name: &str,
    from: Place,
    to_name: &str,
    to: Place,
    kind: DependencyKind,
) -> Option<&'static str> {
    match (from, to) {
        (_, Place::Tool) => Some("no crate may depend on a developer tool"),
        (Place::Tool, _) => Some("developer tools depend on no crate of the workspace"),
        (_, Place::TestSupport) if kind != DependencyKind::Dev => {
            Some("test support crates may only be development dependencies")
        }
        (_, Place::TestSupport) | (Place::TestSupport, Place::Layer(_)) => None,
        (Place::Layer(from), Place::Layer(to)) if to < from => None,
        (Place::Layer(from), Place::Layer(to)) if to == from => {
            if SAME_LAYER.contains(&(from_name, to_name)) {
                None
            } else {
                Some("same layer, and not listed in SAME_LAYER")
            }
        }
        (Place::Layer(_), Place::Layer(_)) => Some("depends on a higher layer"),
    }
}

/// Whether `package` may depend on the third-party crate `dependency`.
fn third_party_allowed(package: &str, dependency: &str) -> bool {
    THIRD_PARTY
        .iter()
        .any(|(name, allowed)| *name == package && allowed.contains(&dependency))
}

/// The generated Markdown section, without the markers.
pub fn markdown() -> String {
    let mut text = String::from("| Layer | Crates | Purpose |\n| --- | --- | --- |\n");
    for layer in LAYERS.iter().rev() {
        let crates: Vec<String> = layer
            .crates
            .iter()
            .map(|name| format!("`{name}`"))
            .collect();
        let _ = writeln!(
            text,
            "| {} | {} | {} |",
            layer.name,
            crates.join(", "),
            layer.purpose
        );
    }
    text.push_str(
        "\nA crate depends only on crates of lower layers, \
         with these exceptions in its own layer:\n\n",
    );
    for (from, to) in SAME_LAYER {
        let _ = writeln!(text, "- `{from}` → `{to}`");
    }
    let support: Vec<String> = TEST_SUPPORT
        .iter()
        .map(|name| format!("`{name}`"))
        .collect();
    let tools: Vec<String> = TOOLS.iter().map(|name| format!("`{name}`")).collect();
    let _ = write!(
        text,
        "\nTest support ({}) is only a development dependency. Tools ({}) use no crate of the \
         workspace.\n\nThird-party crates:\n\n",
        support.join(", "),
        tools.join(", ")
    );
    for (name, allowed) in THIRD_PARTY {
        let crates: Vec<String> = allowed.iter().map(|name| format!("`{name}`")).collect();
        let _ = writeln!(text, "- `{name}`: {}", crates.join(", "));
    }
    text
}

/// `page` with its generated section replaced by `section`.
///
/// # Errors
///
/// [`Error::Format`] when the page lacks the markers.
pub fn replace_section(page: &str, section: &str) -> Result<String> {
    let missing = || Error::Format(format!("{PAGE} lacks the markers {BEGIN} and {END}"));
    let start = page.find(BEGIN).ok_or_else(missing)? + BEGIN.len();
    let end = page[start..].find(END).ok_or_else(missing)? + start;
    Ok(format!("{}\n\n{section}\n{}", &page[..start], &page[end..]))
}

/// Checks the workspace and the architecture page; with `bless`, rewrites
/// the page's generated section instead of comparing it.
///
/// # Errors
///
/// [`Error::Check`] with every problem found, or [`Error::Io`].
pub fn run(workspace: &Workspace, bless: bool) -> Result<()> {
    let mut problems = problems(workspace);
    let path = workspace.root.join(PAGE);
    let page = std::fs::read_to_string(&path)
        .map_err(|error| Error::io(format!("reading {PAGE}"), error))?;
    let expected = replace_section(&page, &markdown())?;
    if bless {
        write_if_changed(&path, &page, &expected)?;
    } else if expected != page {
        problems.push(format!(
            "{PAGE} is out of date: run `cargo xtask check-deps --bless`"
        ));
    }
    if problems.is_empty() {
        println!(
            "check-deps: {} crates, every dependency allowed",
            workspace.packages.len()
        );
        Ok(())
    } else {
        Err(Error::Check {
            check: "check-deps",
            problems,
        })
    }
}

/// Writes `new` to `path` if it differs from `old`.
fn write_if_changed(path: &Path, old: &str, new: &str) -> Result<()> {
    if old == new {
        return Ok(());
    }
    std::fs::write(path, new).map_err(|error| Error::io(format!("writing {PAGE}"), error))?;
    println!("check-deps: rewrote the generated section of {PAGE}");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::workspace::Dependency;
    use std::path::PathBuf;

    fn package(name: &str, dependencies: &[(&str, DependencyKind, bool)]) -> Package {
        Package {
            name: name.to_owned(),
            dir: PathBuf::from(format!("/w/crates/{name}")),
            targets: Vec::new(),
            dependencies: dependencies
                .iter()
                .map(|(name, kind, member)| Dependency {
                    name: (*name).to_owned(),
                    kind: *kind,
                    member: *member,
                })
                .collect(),
        }
    }

    fn problems_of(package: &Package) -> Vec<String> {
        package_problems(package)
    }

    #[test]
    fn a_crate_may_depend_on_lower_layers() {
        let luks = package("zbm-luks", &[("zbm-core", DependencyKind::Normal, true)]);

        assert_eq!(problems_of(&luks), Vec::<String>::new());
    }

    #[test]
    fn a_crate_may_not_depend_on_a_higher_layer() {
        let core = package("zbm-core", &[("zbm-boot", DependencyKind::Normal, true)]);

        assert_eq!(
            problems_of(&core),
            ["zbm-core -> zbm-boot: depends on a higher layer"]
        );
    }

    #[test]
    fn same_layer_edges_must_be_listed() {
        let listed = package("zbm-state", &[("zbm-system", DependencyKind::Normal, true)]);
        let unlisted = package("zbm-system", &[("zbm-state", DependencyKind::Normal, true)]);

        assert_eq!(problems_of(&listed), Vec::<String>::new());
        assert_eq!(
            problems_of(&unlisted),
            ["zbm-system -> zbm-state: same layer, and not listed in SAME_LAYER"]
        );
    }

    #[test]
    fn test_support_is_only_a_development_dependency() {
        let dev = package("zbm-luks", &[("zbm-testutil", DependencyKind::Dev, true)]);
        let normal = package(
            "zbm-luks",
            &[("zbm-testutil", DependencyKind::Normal, true)],
        );

        assert_eq!(problems_of(&dev), Vec::<String>::new());
        assert_eq!(
            problems_of(&normal),
            ["zbm-luks -> zbm-testutil: test support crates may only be development dependencies"]
        );
    }

    #[test]
    fn third_party_crates_must_be_listed_per_crate() {
        let allowed = package(
            "generate-zbm",
            &[("yaml-rust2", DependencyKind::Normal, false)],
        );
        let refused = package("zbm-luks", &[("yaml-rust2", DependencyKind::Normal, false)]);

        assert_eq!(problems_of(&allowed), Vec::<String>::new());
        assert_eq!(
            problems_of(&refused),
            ["zbm-luks -> yaml-rust2: third-party crate not allowed in THIRD_PARTY"]
        );
    }

    #[test]
    fn nothing_depends_on_tools() {
        let zbm = package("zbm", &[("xtask", DependencyKind::Dev, true)]);

        assert_eq!(
            problems_of(&zbm),
            ["zbm -> xtask: no crate may depend on a developer tool"]
        );
    }

    #[test]
    fn crates_missing_from_the_tables_are_reported() {
        let workspace = Workspace {
            root: PathBuf::from("/w"),
            packages: vec![package("zbm-new", &[])],
        };

        let problems = problems(&workspace);

        assert_eq!(
            problems[0],
            "zbm-new is in no layer: add it to xtask/src/deps.rs"
        );
        assert!(
            problems
                .contains(&"zbm-sys is in xtask/src/deps.rs but not in the workspace".to_owned())
        );
    }

    #[test]
    fn the_generated_section_replaces_only_the_text_between_the_markers() {
        let page = format!("# Title\n\n{BEGIN}\nold\n{END}\n\nAfter.\n");

        let new = replace_section(&page, "new\n").unwrap();

        assert_eq!(
            new,
            format!("# Title\n\n{BEGIN}\n\nnew\n\n{END}\n\nAfter.\n")
        );
    }

    #[test]
    fn the_generated_section_lists_layers_from_the_top() {
        let text = markdown();

        let front_ends = text.find("| front ends |").unwrap();
        let unsafe_layer = text.find("| unsafe |").unwrap();
        assert!(front_ends < unsafe_layer);
    }
}
