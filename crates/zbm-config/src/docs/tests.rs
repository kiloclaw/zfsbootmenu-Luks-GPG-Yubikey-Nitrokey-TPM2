#[test]
fn entries_are_indented_under_their_heading() {
    assert_eq!(
        entry("**a**", "\nOne.\n\n.. code-block::\n\n  x\n"),
        "**a**\n\n  One.\n\n  .. code-block::\n\n    x\n"
    );
}

#[test]
fn deprecated_names_say_what_to_use_instead() {
    let cmdline = SECTIONS
        .iter()
        .find(|section| section.name == "cmdline-deprecated")
        .unwrap()
        .render();
    assert!(cmdline.contains("**timeout**\n\n  Deprecated; use **zbm.timeout**.\n"));
    assert!(cmdline.contains("**force_import=1**\n\n"));
    assert!(!cmdline.lines().any(|line| line == "**zbm.timeout**"));
}

#[test]
fn sections_list_the_entries_of_their_source() {
    let render = |name: &str| {
        SECTIONS
            .iter()
            .find(|section| section.name == name)
            .unwrap()
            .render()
    };
    let cmdline = render("cmdline");
    assert!(cmdline.starts_with("**spl_hostid=<hostid>**\n"));
    assert!(cmdline.contains("**zbm.luks_token_wait=<seconds>**"));
    // Deprecated options, options documented within others, and kernel
    // parameters have no entry of their own.
    let headings: Vec<&str> = cmdline
        .lines()
        .filter(|line| line.starts_with("**"))
        .collect();
    for absent in [
        "**timeout**",
        "**zbm.show**",
        "**zbm.force_import=1**",
        "**loglevel**",
    ] {
        assert!(!headings.contains(&absent), "{absent}");
    }
    assert!(render("components").starts_with("**Enabled**\n"));
    assert!(render("efi").contains("**Stub**"));
    assert!(!render("global").contains("**Stub**"));
    assert_eq!(pages().len(), 3);
}

const PAGE: &str = "title\n\
                    .. BEGIN generated by `cargo xtask gen-docs`: crypttab\n\
                    old\n\
                    .. END generated: crypttab\n\
                    tail";

#[test]
fn update_replaces_what_is_between_the_markers() {
    let updated = update(CRYPTTAB, PAGE).unwrap();
    assert!(
        updated.starts_with("title\n.. BEGIN generated by `cargo xtask gen-docs`: crypttab\n\n")
    );
    assert!(updated.contains("\n\n**discard**, **allow-discards**\n"));
    assert!(updated.ends_with("\n\n.. END generated: crypttab\ntail"));
    assert!(!updated.contains("old"));
    // Updating again changes nothing.
    assert_eq!(update(CRYPTTAB, &updated).unwrap(), updated);
    // A page without sections is left alone.
    assert_eq!(update("README.md", PAGE).unwrap(), PAGE);
}

#[test]
fn a_missing_marker_is_an_error() {
    let no_begin = update(CRYPTTAB, "text").unwrap_err();
    assert_eq!(
        no_begin.to_string(),
        "docs/man/zfsbootmenu-crypttab.5.rst: no line \
         `.. BEGIN generated by `cargo xtask gen-docs`: crypttab`"
    );
    let no_end = PAGE.replace(".. END generated: crypttab", "");
    assert!(matches!(
        update(CRYPTTAB, &no_end),
        Err(DocsError::NoEnd { .. })
    ));
}

#[test]
fn splice_writes_a_body_between_the_markers_of_one_section() {
    let page = "head\n\
                .. BEGIN generated by `cargo xtask gen-docs`: keys\n\
                old\n\
                .. END generated: keys\n\
                .. BEGIN generated by `cargo xtask gen-docs`: crypttab\n\
                kept\n\
                .. END generated: crypttab";
    let spliced = splice("page", page, "keys", "**a**\n\n  A.").unwrap();
    assert_eq!(
        spliced,
        "head\n\
         .. BEGIN generated by `cargo xtask gen-docs`: keys\n\
         \n\
         **a**\n\
         \n\
         \x20 A.\n\
         \n\
         .. END generated: keys\n\
         .. BEGIN generated by `cargo xtask gen-docs`: crypttab\n\
         kept\n\
         .. END generated: crypttab"
    );
    assert_eq!(
        splice("page", &spliced, "keys", "**a**\n\n  A.").unwrap(),
        spliced
    );
    assert_eq!(
        splice("page", page, "aliases", "").unwrap_err(),
        DocsError::NoBegin {
            page: "page".to_owned(),
            name: "aliases".to_owned()
        }
    );
    let unclosed = page.replace(".. END generated: keys", "");
    assert_eq!(
        splice("page", &unclosed, "keys", "").unwrap_err(),
        DocsError::NoEnd {
            page: "page".to_owned(),
            name: "keys".to_owned()
        }
    );
}

#[test]
fn splice_refuses_a_marker_on_two_lines_or_an_end_before_the_begin() {
    let section = ".. BEGIN generated by `cargo xtask gen-docs`: keys\n\
                   old\n\
                   .. END generated: keys\n";
    let twice = DocsError::Twice {
        page: "page".to_owned(),
        name: "keys".to_owned(),
    };
    // Two sections of one name: the second would stay as it was.
    let two = format!("{section}between\n{section}");
    assert_eq!(splice("page", &two, "keys", "").unwrap_err(), twice);
    // An opening line twice: the second would be overwritten.
    let doubled = section.replacen(
        "old",
        ".. BEGIN generated by `cargo xtask gen-docs`: keys",
        1,
    );
    assert_eq!(splice("page", &doubled, "keys", "").unwrap_err(), twice);
    let reversed = ".. END generated: keys\n\
                    .. BEGIN generated by `cargo xtask gen-docs`: keys\n";
    assert_eq!(
        splice("page", reversed, "keys", "").unwrap_err(),
        DocsError::NoEnd {
            page: "page".to_owned(),
            name: "keys".to_owned()
        }
    );
}

#[test]
fn the_manual_pages_are_up_to_date() {
    for page in pages() {
        let path = zbm_testkit::repo_root().join(page);
        let text = std::fs::read_to_string(&path).unwrap();
        assert!(
            update(page, &text).unwrap() == text,
            "{page} is out of date: run `cargo xtask gen-docs`"
        );
    }
}

#[test]
fn plain_text_has_no_markup() {
    for section in SECTIONS {
        let text = section.render_plain();
        assert!(!text.is_empty(), "{}", section.name);
        for line in text.lines() {
            assert!(
                !line.contains("**") && !line.contains('`') && !line.contains("\\ "),
                "{}: {line}",
                section.name
            );
            assert!(
                !line.trim_start().starts_with(".. "),
                "{}: {line}",
                section.name
            );
        }
    }
    let rst = "**zbm.skip**\n\n  Skip *it*: ``a *b*``, *\\*.gpg* or **--perf-**\\ *flag*.\n\n  \
               .. note::\n\n    Look.\n\n    .. code-block::\n\n      echo **0** > x\n\n      \
               y\n\n  After.\n";
    assert_eq!(
        plain(rst),
        "zbm.skip\n\n  Skip it: a *b*, *.gpg or --perf-flag.\n\n  Note:\n\n    Look.\n\n      \
         echo **0** > x\n\n      y\n\n  After.\n"
    );
}

#[test]
fn doc_links_keep_their_title() {
    assert_eq!(
        plain("see :doc:`zfsbootmenu-luks(7) </man/zfsbootmenu-luks.7>` and :manpage:`mount(8)`."),
        "see zfsbootmenu-luks(7) and mount(8)."
    );
    let cmdline = SECTIONS
        .iter()
        .find(|section| section.name == "cmdline")
        .unwrap()
        .render_plain();
    assert!(cmdline.contains("see zfsbootmenu-luks(7)."), "{cmdline}");
    assert!(cmdline.contains("recognized by mount(8)"), "{cmdline}");
}
